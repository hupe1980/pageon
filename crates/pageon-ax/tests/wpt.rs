//! WPT role and name conformance (static cases): every element with `data-expectedrole`,
//! `class="ex-generic"` or `data-expectedlabel` in the vendored files (see `tests/wpt/SOURCE`)
//! is checked against pageon's tree, built with layout. Cases pageon fails are listed in
//! `tests/wpt/KNOWN.md`; regenerate with `UPDATE_KNOWN=1 cargo test -p pageon-ax --test wpt`.
//! Cases that need script are not removed: they count as failures.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use pageon_ax::Tree;
use pageon_dom::{Edge, ParseOptions, parse_document};
use pageon_layout::{Layout, Viewport};

fn dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/wpt")
}

fn norm(s: &str) -> String {
    s.split_whitespace().collect::<Vec<_>>().join(" ")
}

#[derive(Default)]
struct Tally {
    pass: usize,
    total: usize,
}

#[test]
fn wpt_roles_and_names() {
    let mut files: Vec<PathBuf> = std::fs::read_dir(dir())
        .unwrap_or_else(|e| panic!("{e}"))
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|x| x == "html"))
        .collect();
    files.sort();
    let (mut roles, mut names) = (Tally::default(), Tally::default());
    let mut failures = String::new();
    for f in &files {
        let file = f
            .file_name()
            .unwrap_or_default()
            .to_string_lossy()
            .to_string();
        let html = std::fs::read_to_string(f).unwrap_or_else(|e| panic!("{e}"));
        let dom = parse_document(&html, ParseOptions::default());
        let layout = Layout::new(&dom, Viewport::default(), &[], None);
        let tree = Tree::build(&dom, Some(&layout));
        let (mut fr, mut fn_) = (Tally::default(), Tally::default());
        for e in dom.traverse(dom.root()) {
            let Edge::Enter(id) = e else { continue };
            let Some(n) = dom.get(id) else { continue };
            let test = n.attr("data-testname").unwrap_or("?");
            let generic = n
                .attr("class")
                .is_some_and(|c| c.split_whitespace().any(|c| c == "ex-generic"));
            if let Some(want) = n.attr("data-expectedrole") {
                let got = tree.role(id).unwrap_or("-");
                fr.total += 1;
                if got == want {
                    fr.pass += 1;
                } else {
                    let _ = writeln!(
                        failures,
                        "- role `{file}` {test}: got `{got}`, want `{want}`"
                    );
                }
            } else if generic {
                let got = tree.role(id).unwrap_or("-");
                fr.total += 1;
                if got == "generic" || got == "none" {
                    fr.pass += 1;
                } else {
                    let _ = writeln!(
                        failures,
                        "- role `{file}` {test}: got `{got}`, want generic"
                    );
                }
            }
            if let Some(want) = n.attr("data-expectedlabel") {
                let got = tree.name(id).unwrap_or_default();
                fn_.total += 1;
                if norm(got) == norm(want) {
                    fn_.pass += 1;
                } else {
                    let _ = writeln!(
                        failures,
                        "- name `{file}` {test}: got {got:?}, want {want:?}"
                    );
                }
            }
        }
        if fr.total + fn_.total > 0 {
            println!(
                "{file:<55} roles {:>3}/{:<3} names {:>3}/{:<3}",
                fr.pass, fr.total, fn_.pass, fn_.total
            );
        }
        roles.pass += fr.pass;
        roles.total += fr.total;
        names.pass += fn_.pass;
        names.total += fn_.total;
    }
    let rp = 100.0 * roles.pass as f64 / roles.total.max(1) as f64;
    let np = 100.0 * names.pass as f64 / names.total.max(1) as f64;
    println!(
        "TOTAL roles {}/{} ({rp:.1} %), names {}/{} ({np:.1} %)",
        roles.pass, roles.total, names.pass, names.total
    );

    let known_path = dir().join("KNOWN.md");
    let header = "# Known WPT failures\n\nGenerated by `UPDATE_KNOWN=1 cargo test -p pageon-ax --test wpt`.\n\n";
    if std::env::var_os("UPDATE_KNOWN").is_some() {
        std::fs::write(&known_path, format!("{header}{failures}"))
            .unwrap_or_else(|e| panic!("{e}"));
    } else {
        let known = std::fs::read_to_string(&known_path).unwrap_or_default();
        let new: Vec<&str> = failures
            .lines()
            .filter(|l| !known.lines().any(|k| k == *l))
            .collect();
        assert!(
            new.is_empty(),
            "new WPT failures (not in KNOWN.md):\n{}",
            new.join("\n")
        );
    }
    assert!(rp >= 90.0, "roles {rp:.1} % (needs ≥ 90 %)");
    assert!(np >= 80.0, "names {np:.1} % (needs ≥ 80 %)");
}
